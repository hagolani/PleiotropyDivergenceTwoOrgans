!CALCULATES OVERLAP AREA BETWEEN TWO POLYGONS
!( MAXIMUM NUMBER OF VERTICES PER POLYGON -200)
!JOHN M. ZERZAN
!STANDARD ALASKA PRODUCTION CO
!P.O. BOX 196612
!ANCHORAGE,AK 99519-6612

SUBROUTINE overlapping(POLY2,ktr2,POLY1,ktr1,fitness)


IMPLICIT NONE
REAL*8, DIMENSION(2000) :: XVAL, YVAL
REAL*8, INTENT(IN) :: POLY1(ktr1,2), POLY2(ktr2,2)
INTEGER, DIMENSION(1000) :: IVERT1, IVERT2
REAL*8, DIMENSION(1000,2) :: PSECT
CHARACTER*40 FNAM
INTEGER, INTENT(IN) :: KTR1, KTR2
INTEGER :: KTR, NINTX
INTEGER :: I, J, K, KTI1, KTI2
INTEGER :: IFLAG, ISECT
REAL*8 :: X0, Y0, X1, Y1, X2, Y2
REAL*8 :: TH1
REAL*8 :: A1, A0, B0, B1
REAL*8 :: S, T
REAL*8 :: DEL, XTST, XTMP
REAL*8 :: AREA, TAREA

REAL*8, INTENT(OUT):: fitness

!FIND THE OVERLAP POLYGON

!LOOK FOR VERTICES IN POLYGON 1 WHICH ARE INTERIOR TO POLYGON 2

    KTI1=0
DO I=1,KTR1
	X0=POLY1(I,1)
	Y0=POLY1(I,2)

	CALL INOUT(POLY2(1,1),POLY2(1,2),KTR2,X0,Y0,TH1)

	IF(ABS(TH1).LT.0.2)CYCLE
	KTI1=KTI1+1
	IVERT1(KTI1)=I
ENDDO 
    
!LOOK FOR VERTICES IN POLYGON 2 WHICH ARE INTERIOR TO POLYGON 1

KTI2=0
DO I=1,KTR2
	X0=POLY2(I,1)
	Y0=POLY2(I,2)
	
	CALL INOUT(POLY1(1,1),POLY1(1,2),KTR1,X0,Y0,TH1)
	
	IF(ABS(TH1).LT.0.2)CYCLE
	KTI2=KTI2+1
	IVERT2(KTI2)=I
ENDDO	

!FIND INTERSECTIONS OF POLYGON 1 POLYGON 2

NINTX=0
DO I=1,KTR1
	A0=POLY1(I,1)
	B0=POLY1(I,2)
	KTR=I+1
	IF(KTR.GT.KTR1)KTR=1

	A1=POLY1(KTR,1)
	B1=POLY1(KTR,2)
        DO J=1,KTR2
	  	 X0=POLY2(J,1)
	  	 Y0=POLY2(J,2)
	 	 KTR=J+1 	 
	  	 IF(KTR.GT.KTR2)KTR=1
	  	 X1=POLY2(KTR,1)
          	 Y1=POLY2(KTR,2)
  
 	         CALL INTERSECT(X0,Y0,X1,Y1,A0,B0,A1,B1,S,T,IFLAG)
                               
		 IF((S.LT.0).OR.(S.GT.1))CYCLE!GOTO 6
		 IF((T.LT.0).OR.(T.GT.1))CYCLE!GOTO 6
		 IF(IFLAG.EQ.-1)CYCLE!GOTO 6
		 
		 !HAVE A LEGAL INTERSECTION
		 
	         NINTX=NINTX+1               
		 PSECT(NINTX,1)=(1-T)*A0+T*A1
		 PSECT(NINTX,2)=(1-T)*B0+T*B1
	ENDDO
ENDDO	  

!HAVE FOUND ALL INTERSECTION (X,Y) FAIRS AND ALL INTERIOR VERTICES
!NOW TAKE THEIR Y VALUES AND SORT THEM TO BUILD THE INTEGRATION COMB
TAREA=0
IF((KTI1+KTI2+NINTX).EQ.0)GOTO 666

DO I=1,KTI1
      YVAL(I)=POLY1(IVERT1(I),2)
ENDDO

DO I=KTI1+1,KTI1+KTI2
           YVAL(I)=POLY2(IVERT2(I-KTI1),2)
ENDDO

DO I=KTI1+KTI2+1,KTI1+KTI2+NINTX
    YVAL(I)=PSECT((I-KTI1-KTI2),2)
ENDDO

KTR=KTI1+KTI2+NINTX
CALL SORT(YVAL,KTR)

!NOV RUN THE COMB



DO I=1,KTR-1
!ACCUMULATE THE VALUE FOR THIS STRIP
          DEL=(YVAL(I+1)-YVAL(I))/2.0
	  IF(DEL.EQ.0) CYCLE!GOTO 10
	  AREA=0
	  Y0=YVAL(I)+DEL
	  
          !CALCULATE SEGMENT CONTAINED IN POLYI AND POLY2
	  
	  ISECT=0
          DO K=1,KTR1
             KTR=K+1
	     IF(KTR.GT.KTR1)KTR=1
             IF((Y0.LT.AMIN1(POLY1(K,2),POLY1(KTR,2))).OR.&
   	     &(Y0.GT.AMAX1(POLY1(K,2),POLY1(KTR,2))))CYCLE
             ISECT=ISECT+1
             XTMP=(Y0-POLY1(K,2))/(POLY1(KTR,2)-POLY1(K,2))
	     XTMP=XTMP*(POLY1(KTR,1)-POLY1(K,1))+POLY1(K,1)
             XVAL(ISECT)=XTMP
          ENDDO

          DO K=1,KTR2
            KTR=K+1
            IF(KTR.GT.KTR2)KTR=1
            IF((Y0.LT.AMIN1(POLY2(K,2),POLY2(KTR,2))).OR.&
            &(Y0.GT.AMAX1(POLY2(K,2),POLY2(KTR,2))))CYCLE!GOTO 12
            ISECT=ISECT+1
            XTMP=(Y0-POLY2(K,2))/(POLY2(KTR,2)-POLY2(K,2))
            XTMP=XTMP*(POLY2(KTR,1)-POLY2(K,1))+POLY2(K,1)
            XVAL(ISECT)=XTMP
          ENDDO
          
          CALL SORT(XVAL,ISECT)

!SEE IF THE SEGMENT IS INSIDE BOTH POLYGONS

	  DO K=1,ISECT - 1
		XTST=(XVAL(K)+XVAL(K+1))/2.0
		IF(XTST.EQ.XVAL(K))CYCLE!GOTO 13

		CALL INOUT(POLY1(1,1),POLY1(1,2),KTR1,XTST,Y0,TH1)

		IF(ABS(TH1).LT.1.0)CYCLE!GOTO 13
		
		CALL INOUT(POLY2(1,1),POLY2(1,2),KTR2,XTST,Y0,TH1)
		
		IF(ABS(TH1).LT. 1)CYCLE!GOTO 13
		AREA=AREA+XVAL(K+1)-XVAL(K)
	  ENDDO		

  	  TAREA=TAREA+(YVAL(I+1)-YVAL(I))*AREA
ENDDO

666     CONTINUE
!WRITE(6,*)' OVERLAP AREA.',TAREA

fitness = TAREA

END SUBROUTINE overlapping

SUBROUTINE INOUT(X,Y,N,X0,Y0,TH1)
!TELLS WHETHER THE POINT XO,YO IS INSIDE
!THE POLYGON ( X ( 1 ) , Y ( 1 ) ) . . . . . (X(N),Y(N)))
!TH1=O IF OUTSIDE
!TH1=PI IF ON THE BORDER
!TH1=2*PI IF INSIDE
!JOHN M. ZERZAN
!STANDARD ALASKA PRODUCTION CO
!P.O. BOX 196612
!ANCHORAGE,AK
!99519-6612
IMPLICIT NONE
INTEGER :: N, I
REAL*8, DIMENSION(N) :: X, Y
REAL*8 :: X0, Y0, TH1
REAL*8 :: PI, PI2
REAL*8 :: XH1, XH2, THETA

!IF NUMBER OF POINTS IN THE POLYGON IS GREATER THAN 200,
!YOU MUST REDIMENSION Z!
COMPLEX Z(1001),Z0


IF(N.GT. 1000)WRITE(6,*)' POLYGON TOO BIG IN SUBROUTINE INOUT'
PI=3.1415926536
PI2=2.*3.1415926536
Z0=CMPLX(X0,Y0)

DO I=1,N
	Z(I)=CMPLX(X(I),Y(I))
!SEE IF THE POINT IS EXACTLY ON A VERTEX
	IF(Z(I).EQ.Z0)GOTO 987
ENDDO 
!1 CONTINUE

Z(N+1)=Z(1)
TH1=0

DO I=1,N
	XH1=AIMAG(CLOG((Z(I+1)-Z0)/CABS(Z(I+1)-Z0)))
	IF(XH1.LT.0)XH1=XH1+PI2
	XH2=AIMAG(CLOG((Z(I)-Z0)/CABS(Z(I)-Z0)))
	IF(XH2.LT.0)XH2=XH2+PI2
	THETA=XH1-XH2
!	THETA=IFLAG*THETA
	IF(THETA.LT.-PI)THETA=THETA+PI2
	IF((ABS(ABS(THETA)-PI).LT.0.00001))GOTO 987
	IF(THETA.GT.PI)THETA=THETA-PI2
	TH1=TH1+THETA
ENDDO
!2 CONTINUE

GOTO 666

987 CONTINUE
TH1=PI

666 CONTINUE
TH1=abs(TH1)

END SUBROUTINE INOUT

SUBROUTINE INTERSECT(X0,Y0,X1,Y1,A0,B0,A1,B1,S,T,IFLAG)

!CALCULATE S,T SUCH THAT
!{[(I-S)XO+SXIJ,[(I-S)YO+SYIJ}={[(I-T)AO+TAI],[(I-T)BO.TBI)]}
!WHERE THE {..}-{..}
!THE LINE SEGMENTS
!POINT PAIRS ARE THE INTERSECTIONS OF
!JOHN M. ZERZAN
!STANDARD ALASKA PRODUCTION CO
!P.O. BOX 196612
!ANCHORAGE,AK 99519-6612

IMPLICIT NONE
REAL*8, INTENT(OUT) :: S, T
REAL*8, INTENT(IN) :: X0,Y0,A0,B0,X1,Y1,A1,B1
INTEGER :: IFLAG
REAL*8 :: CHECK

IFLAG=0 
CHECK=(X0-X1)*(B1-B0)-(A1-A0)*(Y0-Y1)
IF(CHECK.NE.0)GOTO 1

!GET HERE IF LINES ARE PARALLEL

IFLAG=-1
RETURN
                   
1 CONTINUE
S=(B1-B0)*(X0-A0)+(Y0-B0)*(A0-A1) 
T=(Y1-Y0)*(X0-A0)+(Y0-B0)*(X0-X1) 
S=S/CHECK
T=T/CHECK 

END SUBROUTINE INTERSECT

SUBROUTINE SORT(S,KTR)

IMPLICIT NONE
REAL*8, DIMENSION(KTR) :: S
INTEGER :: I, J, KTR
REAL*8 :: TEMP
!JOHN M. ZERZAN
!STANDARD ALASKA PRODUCTION CO
!P.O. BOX 196612
!ANCHORAGE,AK 99519-6612

DO I=1,KTR-1
	TEMP=S(I)
	DO J=I+1,KTR
		IF(S(J).GT.TEMP)CYCLE!GOTO 1
		S(I)=S(J)
		S(J)=TEMP
		TEMP=S(I)
	ENDDO
ENDDO			

END SUBROUTINE SORT

END MODULE OVERLAP
